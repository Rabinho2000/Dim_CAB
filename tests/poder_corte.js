/* poder de corte na interface: por omissão "não verificado"; com um PT de 2500 kVA, o E1.2 de 42 kA fica "a rever" com a explicação;
   com 630 kVA tudo cumpre. Gera tests/poder_corte.png. Tem de dar "ERR []". */
const { chromium } = require('playwright');const fs=require('fs');
(async()=>{const errs=[];const check=(ok,msg)=>{console.log(ok?'ok  ':'FALHA',msg);if(!ok)errs.push(msg);};
const b=await chromium.launch();const p=await b.newPage({viewport:{width:1400,height:1000}});p.on('pageerror',e=>errs.push(e.message));
const html=fs.readFileSync(__dirname+'/../cabos-rt.html','utf8').replace(/<link[^>]*fonts[^>]*>/g,'');
await p.setContent('<!doctype html><meta charset=utf-8><body>'+html);
const kpis=()=>p.$eval('#kpis',e=>e.innerText.replace(/\s+/g,' '));
check(/Poder de corte não verificado/i.test(await kpis()),'por omissão: "Poder de corte: não verificado"');
check(await p.$eval('[data-icu=pt]',e=>e.hidden),'os campos só aparecem ao escolher o modo');
await p.selectOption('#icu-modo','pt');await p.fill('#icu-sn','2500');
check(!(await p.$eval('[data-icu=pt]',e=>e.hidden)),'aparece a potência do PT');
check(/Icc no ponto de ligação 57,9 ?kA/i.test(await kpis()),`KPI com a Icc do PT (${(await kpis()).match(/Icc[^A-Z]*kA/i)})`);
const rows=await p.$$eval('#res-body tr',t=>t.map(r=>r.innerText.replace(/\s+/g,' ')));
const f=rows.find(r=>/QInterligação → Qentrada/.test(r))||'';
check(/Poder de corte insuficiente: Icc no local 57,9 kA > Icu 42 kA/.test(f)&&/PODER DE CORTE/i.test(f),'o E1.2 de 42 kA fica a rever com a explicação');
check(/Icc no local [\d,]+ kA ≤ Icu 36 kA/.test(rows.find(r=>/Inversor 1/.test(r))||''),'os disjuntores dos inversores mostram a Icc no local e cumprem');
check(/A REVER [1-9]/i.test(await kpis()),'conta nos circuitos a rever');
await (await p.$('#res-body')).screenshot({path:__dirname+'/poder_corte.png'});
await p.fill('#icu-sn','630');check(!(await p.$$eval('#res-body tr',t=>t.some(r=>/insuficiente/.test(r.innerText)))),'com 630 kVA todos cumprem');
await p.selectOption('#icu-modo','');check(/não verificado/i.test(await kpis()),'volta a "não verificado"');
console.log('ERR',errs);await b.close();process.exit(errs.length?1:0);})();
